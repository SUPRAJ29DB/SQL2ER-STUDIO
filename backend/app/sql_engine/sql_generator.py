from typing import List
from app.models.schema_models import SchemaDefinition, TableDefinition, ColumnDefinition

class SQLGenerator:
    """Generates standardized SQL DDL from SchemaDefinition for various dialects."""

    @classmethod
    def generate_ddl(cls, schema: SchemaDefinition, dialect: str = "postgresql") -> str:
        dialect_lower = (dialect or "postgresql").lower()
        output = [
            f"-- ========================================================",
            f"-- Generated by SQL2ER STUDIO",
            f"-- Dialect: {dialect_lower.upper()}",
            f"-- Tables: {len(schema.tables)} | Relationships: {len(schema.relationships)}",
            f"-- ========================================================\n"
        ]

        if dialect_lower == "postgresql":
            output.append("-- Enable UUID extension if needed")
            output.append('CREATE EXTENSION IF NOT EXISTS "uuid-ossp";\n')

        # 1. CREATE TABLES
        for table in schema.tables:
            table_ddl = cls._generate_table_ddl(table, dialect_lower)
            output.append(table_ddl)
            output.append("")

        # 2. ALTER TABLE ADD FOREIGN KEYS (for PostgreSQL and MySQL)
        if dialect_lower in ["postgresql", "mysql"]:
            fk_statements = []
            for rel in schema.relationships:
                action_del = f" ON DELETE {rel.on_delete}" if rel.on_delete and rel.on_delete != "NO ACTION" else ""
                action_upd = f" ON UPDATE {rel.on_update}" if rel.on_update and rel.on_update != "NO ACTION" else ""
                stmt = (
                    f"ALTER TABLE {table_quote(rel.source_table, dialect_lower)} "
                    f"ADD CONSTRAINT fk_{rel.source_table}_{rel.source_column} "
                    f"FOREIGN KEY ({table_quote(rel.source_column, dialect_lower)}) "
                    f"REFERENCES {table_quote(rel.target_table, dialect_lower)} ({table_quote(rel.target_column, dialect_lower)})"
                    f"{action_del}{action_upd};"
                )
                fk_statements.append(stmt)

            if fk_statements:
                output.append("-- Referential Integrity & Foreign Keys")
                output.extend(fk_statements)
                output.append("")

        return "\n".join(output)

    @classmethod
    def _generate_table_ddl(cls, table: TableDefinition, dialect: str) -> str:
        lines = []
        lines.append(f"CREATE TABLE {table_quote(table.name, dialect)} (")

        col_defs = []
        for col in table.columns:
            col_str = f"    {table_quote(col.name, dialect)} {map_data_type(col.data_type, dialect)}"

            if col.is_primary_key and dialect == "sqlite" and len(table.primary_keys) <= 1:
                col_str += " PRIMARY KEY"
                if col.is_auto_increment:
                    col_str += " AUTOINCREMENT"
            elif col.is_primary_key and dialect == "mysql" and len(table.primary_keys) <= 1 and col.is_auto_increment:
                col_str += " AUTO_INCREMENT"
            elif col.is_auto_increment and dialect == "postgresql":
                col_str = f"    {table_quote(col.name, dialect)} SERIAL"

            if not col.is_nullable and not (col.is_primary_key and dialect == "sqlite"):
                col_str += " NOT NULL"

            if col.is_unique and not col.is_primary_key:
                col_str += " UNIQUE"

            if col.default_value is not None:
                col_str += f" DEFAULT {col.default_value}"

            # Inline foreign keys for SQLite
            if dialect == "sqlite" and col.references_table and col.references_column:
                col_str += f" REFERENCES {col.references_table}({col.references_column})"

            col_defs.append(col_str)

        # Primary Key constraint
        if dialect != "sqlite" or len(table.primary_keys) > 1:
            if table.primary_keys:
                pk_cols = ", ".join(table_quote(k, dialect) for k in table.primary_keys)
                col_defs.append(f"    CONSTRAINT pk_{table.name} PRIMARY KEY ({pk_cols})")

        lines.append(",\n".join(col_defs))
        lines.append(");")
        return "\n".join(lines)


def table_quote(name: str, dialect: str) -> str:
    if dialect == "mysql":
        return f"`{name}`"
    elif dialect == "postgresql":
        return f'"{name}"'
    return f'"{name}"'


def map_data_type(dtype: str, dialect: str) -> str:
    dtype_upper = dtype.upper()
    if dialect == "sqlite":
        if any(t in dtype_upper for t in ["INT", "SERIAL", "TINYINT", "BIGINT"]):
            return "INTEGER"
        if any(t in dtype_upper for t in ["CHAR", "TEXT", "VARCHAR", "UUID", "JSON"]):
            return "TEXT"
        if any(t in dtype_upper for t in ["REAL", "FLOAT", "DOUBLE", "DECIMAL", "NUMERIC"]):
            return "REAL"
        if any(t in dtype_upper for t in ["BLOB", "BYTEA"]):
            return "BLOB"
        return "TEXT"
    elif dialect == "postgresql":
        if "TINYINT(1)" in dtype_upper or "BOOLEAN" in dtype_upper:
            return "BOOLEAN"
        if "DATETIME" in dtype_upper:
            return "TIMESTAMP"
    return dtype

